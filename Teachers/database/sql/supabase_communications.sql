-- Chat, message, and call tables for the shared Students and Teachers database.
-- Idempotent. Does not drop tables or delete rows.
-- Requires public.users to already exist.
-- Row level security is enabled with no policies. Laravel's database role bypasses it.
-- The anon and authenticated API roles cannot read these tables.

CREATE TABLE IF NOT EXISTS public.chats (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type varchar(20) NOT NULL,
    name varchar(255) NULL,
    created_by bigint NULL REFERENCES public.users (id) ON DELETE SET NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL
);

CREATE TABLE IF NOT EXISTS public.chat_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL REFERENCES public.chats (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    joined_at timestamptz NULL,
    last_read_at timestamptz NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL,
    CONSTRAINT chat_participants_chat_id_user_id_unique UNIQUE (chat_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NOT NULL REFERENCES public.chats (id) ON DELETE CASCADE,
    sender_id bigint NULL REFERENCES public.users (id) ON DELETE SET NULL,
    message_type varchar(20) NOT NULL DEFAULT 'text',
    body text NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL
);

CREATE INDEX IF NOT EXISTS messages_chat_id_created_at_index
    ON public.messages (chat_id, created_at);

CREATE TABLE IF NOT EXISTS public.calls (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id bigint NULL REFERENCES public.chats (id) ON DELETE SET NULL,
    caller_id bigint NULL REFERENCES public.users (id) ON DELETE SET NULL,
    call_type varchar(20) NOT NULL,
    status varchar(20) NOT NULL DEFAULT 'ringing',
    started_at timestamptz NULL,
    ended_at timestamptz NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL
);

CREATE INDEX IF NOT EXISTS calls_caller_id_status_index
    ON public.calls (caller_id, status);

CREATE TABLE IF NOT EXISTS public.call_participants (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    call_id bigint NOT NULL REFERENCES public.calls (id) ON DELETE CASCADE,
    user_id bigint NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    status varchar(20) NOT NULL DEFAULT 'invited',
    joined_at timestamptz NULL,
    left_at timestamptz NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL,
    CONSTRAINT call_participants_call_id_user_id_unique UNIQUE (call_id, user_id)
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'chats_type_check') THEN
        ALTER TABLE public.chats ADD CONSTRAINT chats_type_check CHECK (type IN ('direct', 'group'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'messages_type_check') THEN
        ALTER TABLE public.messages ADD CONSTRAINT messages_type_check CHECK (message_type IN ('text', 'image', 'file', 'system'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'calls_type_check') THEN
        ALTER TABLE public.calls ADD CONSTRAINT calls_type_check CHECK (call_type IN ('voice', 'video'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'calls_status_check') THEN
        ALTER TABLE public.calls ADD CONSTRAINT calls_status_check CHECK (status IN ('ringing', 'ongoing', 'ended', 'missed', 'declined'));
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'call_participants_status_check') THEN
        ALTER TABLE public.call_participants ADD CONSTRAINT call_participants_status_check CHECK (status IN ('invited', 'joined', 'left', 'missed', 'declined'));
    END IF;
END $$;

ALTER TABLE public.chats ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.chat_participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.calls ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.call_participants ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.chats FROM anon, authenticated;
REVOKE ALL ON TABLE public.chat_participants FROM anon, authenticated;
REVOKE ALL ON TABLE public.messages FROM anon, authenticated;
REVOKE ALL ON TABLE public.calls FROM anon, authenticated;
REVOKE ALL ON TABLE public.call_participants FROM anon, authenticated;
