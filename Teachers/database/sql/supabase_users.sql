-- Shared users table for the Students and Teachers Laravel applications.
-- Review and run this manually in the Supabase SQL Editor.
-- It is idempotent: it does not drop tables, delete rows, or reset passwords.
--
-- Connection to use from Laravel:
--   Session pooler (port 5432) or the direct database host.
--   Do not use the transaction pooler (port 6543); Laravel uses prepared statements.
--   Require SSL: DB_SSLMODE=require
--
-- The postgres database role used by Laravel bypasses row level security.
-- The anon and authenticated API roles have no policies, so they cannot read password hashes.

CREATE TABLE IF NOT EXISTS public.users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id varchar(30) NULL,
    username varchar(30) NULL,
    name varchar(255) NULL,
    password varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    remember_token varchar(100) NULL,
    created_at timestamptz NULL,
    updated_at timestamptz NULL
);

ALTER TABLE public.users ADD COLUMN IF NOT EXISTS student_id varchar(30) NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS username varchar(30) NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS name varchar(255) NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS password varchar(255);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS role varchar(20);
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS is_active boolean NOT NULL DEFAULT true;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS remember_token varchar(100) NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS created_at timestamptz NULL;
ALTER TABLE public.users ADD COLUMN IF NOT EXISTS updated_at timestamptz NULL;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'users_role_check'
    ) THEN
        ALTER TABLE public.users
            ADD CONSTRAINT users_role_check
            CHECK (role IN ('students', 'teachers'));
    END IF;
END $$;

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'users_identifier_check'
    ) THEN
        ALTER TABLE public.users
            ADD CONSTRAINT users_identifier_check
            CHECK (
                (role = 'students' AND student_id IS NOT NULL)
                OR (role = 'teachers' AND username IS NOT NULL)
            );
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS users_student_id_unique
    ON public.users (student_id)
    WHERE student_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS users_username_unique
    ON public.users (username)
    WHERE username IS NOT NULL;

CREATE INDEX IF NOT EXISTS users_role_index
    ON public.users (role);

ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.users FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.users_id_seq FROM anon, authenticated;

