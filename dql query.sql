create table if not exists public.users (
  id bigint generated by default as identity not null,
  student_id character varying(30) null,
  username character varying(30) null,
  name character varying(255) null,
  password character varying(255) not null,
  role character varying(20) not null,
  is_active boolean not null default true,
  remember_token character varying(100) null,
  created_at timestamp with time zone null,
  updated_at timestamp with time zone null,
  last_seen timestamp without time zone null,
  online_status character varying(20) null default 'offline'::character varying,
  profile_image_url text null,
  profile_image_public_id character varying(255) null,
  constraint users_pkey primary key (id)
) tablespace pg_default;

create index if not exists users_role_is_active_name_index on public.users using btree (role, is_active, name) tablespace pg_default;

create unique index if not exists users_student_id_unique on public.users (student_id) where student_id is not null;

create unique index if not exists users_username_unique on public.users (username) where username is not null;

create table if not exists public.cache (
  key character varying(255) not null,
  value text not null,
  expiration integer not null,
  constraint cache_pkey primary key (key)
) tablespace pg_default;

create table if not exists public.conversations (
  id bigserial not null,
  conversation_type character varying(20) not null default 'private'::character varying,
  name character varying(255) null,
  default_group_type character varying(40) null,
  tenant_id bigint null,
  max_members integer null,
  avatar_url character varying(255) null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  avatar_public_id character varying(255) null,
  constraint conversations_pkey primary key (id)
) tablespace pg_default;

create index if not exists conversations_conversation_type_index on public.conversations using btree (conversation_type) tablespace pg_default;

create table if not exists public.conversation_participants (
  id bigserial not null,
  conversation_id bigint not null,
  user_id bigint not null,
  user_type character varying(30) not null,
  participant_role character varying(20) not null default 'member'::character varying,
  joined_at timestamp without time zone null,
  last_read_at timestamp without time zone null,
  last_read_message_id bigint null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  constraint conversation_participants_pkey primary key (id),
  constraint conversation_participants_unique unique (conversation_id, user_id, user_type),
  constraint conversation_participants_conversation_id_foreign foreign key (conversation_id) references conversations (id) on delete cascade,
  constraint conversation_participants_user_id_foreign foreign key (user_id) references users (id) on delete cascade
) tablespace pg_default;

create index if not exists conversation_participants_user_id_conversation_id_index on public.conversation_participants using btree (user_id, conversation_id) tablespace pg_default;

create index if not exists conversation_participants_conversation_id_user_id_index on public.conversation_participants using btree (conversation_id, user_id) tablespace pg_default;

create table if not exists public.messages (
  id bigserial not null,
  chat_id bigint null,
  sender_id bigint null,
  message_type character varying(20) not null default 'text'::character varying,
  body text null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  conversation_id bigint null,
  sender_type character varying(30) null,
  edited_at timestamp without time zone null,
  deleted_for_all_at timestamp without time zone null,
  constraint messages_pkey primary key (id),
  constraint messages_sender_id_foreign foreign key (sender_id) references users (id) on delete set null,
  constraint messages_type_check check (
    (message_type)::text = any (
      array[
        'text'::character varying,
        'image'::character varying,
        'file'::character varying,
        'system'::character varying,
        'call'::character varying
      ]::text[]
    )
  )
) tablespace pg_default;

create index if not exists messages_chat_id_created_at_index on public.messages using btree (chat_id, created_at) tablespace pg_default;

create index if not exists messages_conversation_id_id_index on public.messages using btree (conversation_id, id desc) tablespace pg_default;

create index if not exists messages_conversation_id_created_at_index on public.messages using btree (conversation_id, created_at desc) tablespace pg_default;

create table if not exists public.message_attachments (
  id bigserial not null,
  message_id bigint not null,
  disk character varying(255) null,
  path text null,
  original_name character varying(255) null,
  mime_type character varying(255) null,
  size bigint null,
  kind character varying(20) null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  public_id character varying(255) null,
  constraint message_attachments_pkey primary key (id),
  constraint message_attachments_message_id_foreign foreign key (message_id) references messages (id) on delete cascade
) tablespace pg_default;

create table if not exists public.message_hides (
  id bigserial not null,
  message_id bigint not null,
  user_id bigint not null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  user_type character varying(30) null,
  constraint message_hides_pkey primary key (id),
  constraint message_hides_message_id_user_id_unique unique (message_id, user_id),
  constraint message_hides_message_id_foreign foreign key (message_id) references messages (id) on delete cascade,
  constraint message_hides_user_id_foreign foreign key (user_id) references users (id) on delete cascade
) tablespace pg_default;

create table if not exists public.calls (
  id bigserial not null,
  chat_id bigint null,
  caller_id bigint null,
  call_type character varying(20) not null,
  status character varying(20) not null default 'ringing'::character varying,
  started_at timestamp without time zone null,
  ended_at timestamp without time zone null,
  created_at timestamp without time zone null,
  updated_at timestamp without time zone null,
  conversation_id bigint null,
  caller_type character varying(30) null,
  receiver_id bigint null,
  receiver_type character varying(30) null,
  answered_at timestamp without time zone null,
  duration_seconds integer null,
  end_reason character varying(32) null,
  ended_by bigint null,
  is_group boolean null default false,
  constraint calls_pkey primary key (id),
  constraint calls_caller_id_foreign foreign key (caller_id) references users (id) on delete set null,
  constraint calls_status_check check (
    (status)::text = any (
      array[
        'ringing'::character varying,
        'accepted'::character varying,
        'rejected'::character varying,
        'missed'::character varying,
        'cancelled'::character varying,
        'ended'::character varying,
        'ongoing'::character varying,
        'declined'::character varying
      ]::text[]
    )
  ),
  constraint calls_type_check check (
    (call_type)::text = any (
      array[
        'voice'::character varying,
        'video'::character varying
      ]::text[]
    )
  )
) tablespace pg_default;

create index if not exists calls_receiver_status_index on public.calls using btree (receiver_id, status) tablespace pg_default;

create index if not exists calls_conversation_id_idx on public.calls using btree (conversation_id) tablespace pg_default;

create index if not exists calls_status_idx on public.calls using btree (status) tablespace pg_default;

create index if not exists calls_caller_lookup_idx on public.calls using btree (caller_id, caller_type) tablespace pg_default;

create index if not exists calls_receiver_lookup_idx on public.calls using btree (receiver_id, receiver_type) tablespace pg_default;

create index if not exists calls_started_at_idx on public.calls using btree (started_at) tablespace pg_default;

create index if not exists calls_caller_id_status_index on public.calls using btree (caller_id, status) tablespace pg_default;

create index if not exists calls_status_ended_at_index on public.calls using btree (status, ended_at) tablespace pg_default;

create index if not exists calls_conversation_created_idx on public.calls using btree (conversation_id, created_at) tablespace pg_default;

